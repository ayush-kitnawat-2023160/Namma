#!/usr/bin/env python3
"""Reuse NextGen SfM without treating automatic calibration as ground truth.

GeoCalib's rectified intrinsics remain the initialization. Only a supplied camera
profile is fixed during bundle adjustment; automatically estimated focal lengths
are optimized against the image tracks. The baseline scripts are not modified.
"""
from __future__ import annotations

import argparse
import builtins
import copy
import importlib.util
import json
import math
import sys
from dataclasses import dataclass
from pathlib import Path


MAX_VIEWS = 160
IMAGE_SUFFIXES = {".jpg", ".jpeg", ".png"}


@dataclass(frozen=True)
class CalibrationPolicy:
    camera: dict | None
    fixed: bool
    source: str


def calibration_policy(camera: dict, source_profile: dict | None = None) -> CalibrationPolicy:
    """Separate rectification availability from calibration measurement provenance."""
    if not camera.get("known_calibration"):
        return CalibrationPolicy(None, False, "vggt_shared_initialization")
    required = ("fx", "fy", "cx", "cy", "width", "height")
    for field in required:
        try:
            value = float(camera[field])
        except (KeyError, TypeError, ValueError) as exc:
            raise ValueError(f"Prepared camera has no valid {field}") from exc
        if not math.isfinite(value):
            raise ValueError(f"Prepared camera {field} must be finite")
        if field in {"fx", "fy", "width", "height"} and value <= 0:
            raise ValueError(f"Prepared camera {field} must be positive")
    if camera.get("distortion_model") != "pinhole_rectified":
        raise ValueError("SfM requires the prepared pinhole_rectified camera, not a raw camera profile")

    # prepare_scene.py's legacy known_calibration flag means "a profile was used",
    # including profiles generated by GeoCalib. Inspect its actual provenance.
    profile_path = str(camera.get("source_profile", "")).replace("\\", "/")
    profile = source_profile or {}
    provenance = " ".join(
        str(value) for value in (
            camera.get("source", ""), camera.get("name", ""),
            camera.get("calibration_source", ""), profile.get("name", ""),
            profile.get("source", ""),
        )
    ).lower()
    automatic = (
        "00_calibration" in Path(profile_path).parts
        or "geocalib" in provenance
        or "geocalib" in profile_path.lower()
        or camera.get("calibration_estimated") is True
        or profile.get("calibration_estimated") is True
    )
    # Missing provenance is insufficient evidence to freeze a network estimate.
    fixed = bool(profile_path) and not automatic
    source = (
        "geocalib_rectified_initialization" if automatic else
        "supplied_profile_rectified" if fixed else
        "unverified_rectified_initialization"
    )
    return CalibrationPolicy(dict(camera), fixed, source)


def load_policy(scene_root: Path) -> CalibrationPolicy:
    import yaml

    camera_path = scene_root / "01_frames" / "camera.yaml"
    if not camera_path.is_file():
        return CalibrationPolicy(None, False, "vggt_shared_initialization")
    camera = yaml.safe_load(camera_path.read_text()) or {}
    if not isinstance(camera, dict):
        raise ValueError(f"Camera document must be a mapping: {camera_path}")
    source_profile = None
    source_path = Path(str(camera.get("source_profile", "")))
    if source_path.is_file():
        source_profile = yaml.safe_load(source_path.read_text()) or {}
        if not isinstance(source_profile, dict):
            raise ValueError(f"Source profile must be a mapping: {source_path}")
    return calibration_policy(camera, source_profile)


class ColmapPolicyAdapter:
    """Apply explicit final BA policy without patching the shared pycolmap module."""

    def __init__(self, module, policy: CalibrationPolicy):
        self.module = module
        self.policy = policy

    def __getattr__(self, name):
        return getattr(self.module, name)

    def bundle_adjustment(self, model, options):
        options.refine_focal_length = not self.policy.fixed
        options.refine_principal_point = False
        # Frames were rectified already. Optimizing a distortion parameter again
        # would change the image model rather than recover the original lens.
        options.refine_extra_params = False
        result = self.module.bundle_adjustment(model, options)
        # Point3D.error is stored on disk and is consumed by the geometry gate.
        # Recompute it using the final optimized cameras and points.
        model.update_point_3d_errors()
        return result


def run_backend(backend, args, policy: CalibrationPolicy) -> None:
    """Wrap the unchanged baseline main while separating its two camera decisions."""
    output = args.output or args.scene_root / "03_sfm"
    original_camera = backend.read_camera
    original_reference = backend.make_vggt_reference_model
    original_colmap = backend.pycolmap
    original_feature_conf = backend.extract_features.confs["superpoint_max"]
    had_print = "print" in vars(backend)
    original_print = vars(backend).get("print")
    original_argv = sys.argv

    def make_reference(vggt_file, image_names, _legacy_camera, reference_output):
        if policy.camera is not None:
            with backend.np.load(vggt_file) as data:
                actual = (int(data["original_width"].item()), int(data["original_height"].item()))
            declared = (int(policy.camera["width"]), int(policy.camera["height"]))
            if actual != declared:
                raise RuntimeError(f"Rectified camera resolution {declared} differs from VGGT inputs {actual}")
        model = original_reference(vggt_file, image_names, policy.camera, reference_output)
        metadata_path = reference_output / "metadata.json"
        metadata = json.loads(metadata_path.read_text())
        metadata["intrinsic_source"] = policy.source
        metadata["focal_refinement"] = not policy.fixed
        metadata_path.write_text(json.dumps(metadata, indent=2) + "\n")
        return model

    def precision_print(*values, **kwargs):
        if values and values[0] == "Camera initialization:":
            values = (
                "Camera initialization:", policy.source,
                "; focal fixed" if policy.fixed else "; focal refined by bundle adjustment",
            )
        return builtins.print(*values, **kwargs)

    feature_conf = copy.deepcopy(original_feature_conf)
    feature_conf.setdefault("model", {})["max_keypoints"] = args.max_keypoints
    feature_conf.setdefault("preprocessing", {})["resize_max"] = args.feature_max_size
    try:
        # Legacy uses this result only for calibration trust and mapper options.
        # The reference callback above independently preserves estimated K.
        backend.read_camera = lambda _path: policy.camera if policy.fixed else None
        backend.make_vggt_reference_model = make_reference
        backend.pycolmap = ColmapPolicyAdapter(original_colmap, policy)
        backend.extract_features.confs["superpoint_max"] = feature_conf
        backend.print = precision_print
        sys.argv = [
            "sfm_lightglue.py",
            "--images", str(args.scene_root / "01_frames" / "images"),
            "--camera", str(args.scene_root / "01_frames" / "camera.yaml"),
            "--vggt", str(args.scene_root / "02_vggt" / "cameras.npz"),
            "--output", str(output),
            "--temporal-window", str(args.temporal_window),
            "--visual-neighbors", str(args.visual_neighbors),
        ]
        backend.main()
    finally:
        sys.argv = original_argv
        backend.read_camera = original_camera
        backend.make_vggt_reference_model = original_reference
        backend.pycolmap = original_colmap
        backend.extract_features.confs["superpoint_max"] = original_feature_conf
        if had_print:
            backend.print = original_print
        else:
            del backend.print

    summary_path = output / "summary.json"
    summary = json.loads(summary_path.read_text())
    summary["calibration"] = {
        "source": policy.source,
        "rectified_intrinsics_initialized": policy.camera is not None,
        "focal_refinement": not policy.fixed,
        "principal_point_refinement": False,
        "distortion_refinement": False,
        "source_profile": policy.camera.get("source_profile") if policy.camera else None,
    }
    summary["feature_max_keypoints"] = args.max_keypoints
    summary["feature_resize_max"] = args.feature_max_size
    summary["validation_note"] = (
        "VGGT supplies all camera poses, so registration_fraction is not an independent "
        "geometry accuracy check. The precision geometry quality gate must pass before MVS."
    )
    summary_path.write_text(json.dumps(summary, indent=2) + "\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--scene-root", type=Path, required=True)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--temporal-window", type=int, default=8)
    parser.add_argument("--visual-neighbors", type=int, default=12)
    parser.add_argument("--max-keypoints", type=int, default=8192)
    parser.add_argument("--feature-max-size", type=int, default=1600)
    parser.add_argument("--backend", type=Path, default=Path("/opt/namma-nextgen/scripts/sfm_lightglue.py"))
    args = parser.parse_args()
    if not 1 <= args.temporal_window <= 10 or not 0 <= args.visual_neighbors <= 16:
        parser.error("temporal-window must be 1..10 and visual-neighbors 0..16")
    if not 512 <= args.max_keypoints <= 8192 or not 512 <= args.feature_max_size <= 1600:
        parser.error("max-keypoints must be 512..8192 and feature-max-size 512..1600")
    images = args.scene_root / "01_frames" / "images"
    if not images.is_dir():
        parser.error(f"Prepared image directory missing: {images}")
    count = sum(path.is_file() and path.suffix.lower() in IMAGE_SUFFIXES for path in images.iterdir())
    if not 3 <= count <= MAX_VIEWS:
        parser.error(f"Precision SfM requires 3..{MAX_VIEWS} selected images; found {count}")
    if not (args.scene_root / "02_vggt" / "cameras.npz").is_file():
        parser.error("VGGT cameras.npz is missing; run the VGGT initialization first")
    if not args.backend.is_file():
        parser.error(f"NextGen SfM backend missing: {args.backend}")
    policy = load_policy(args.scene_root)
    spec = importlib.util.spec_from_file_location("namma_nextgen_sfm", args.backend)
    if spec is None or spec.loader is None:
        parser.error(f"Cannot import NextGen SfM backend: {args.backend}")
    backend = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(backend)
    run_backend(backend, args, policy)


if __name__ == "__main__":
    main()
